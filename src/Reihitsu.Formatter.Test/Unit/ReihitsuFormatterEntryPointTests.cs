    /// <summary>
    /// Finds the method or type declaration with the given name
    /// </summary>
    /// <param name="root">The root to search</param>
    /// <param name="name">The declared name</param>
    /// <returns>The declaration</returns>
    private static SyntaxNode FindDeclaration(SyntaxNode root, string name)
    {
        return root.DescendantNodes()
                   .First(node => (node is MethodDeclarationSyntax method && method.Identifier.Text == name)
                                  || (node is BaseTypeDeclarationSyntax type && type.Identifier.Text == name));
    }

    /// <summary>
    /// Formats the named target through <see cref="ReihitsuFormatter.FormatNodeInDocumentAsync"/>, or through
    /// <see cref="ReihitsuFormatter.FormatNodeInDocumentWithContextAsync"/> when a context name is given, under every line ending
    /// </summary>
    /// <param name="source">The document source</param>
    /// <param name="targetName">The name of the target declaration</param>
    /// <param name="contextName">The name of the context declaration, or <see langword="null"/> for no context</param>
    /// <param name="assert">The assertion on the input document and the result</param>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    private async Task FormatNodeInDocument(string source, string targetName, string contextName, Func<Document, Document, string, Task> assert)
    {
        foreach (var endOfLine in _lineEndings)
        {
            using (var workspace = new AdhocWorkspace())
            {
                var project = workspace.AddProject("TestProject", LanguageNames.CSharp);
                var document = project.AddDocument("Test.cs", SourceText.From(NormalizeLineEndings(source, endOfLine)));
                var root = await document.GetSyntaxRootAsync(TestContext.CancellationToken);

                Assert.IsNotNull(root);

                var target = FindDeclaration(root, targetName);
                var result = contextName == null
                                 ? await ReihitsuFormatter.FormatNodeInDocumentAsync(document, target, TestContext.CancellationToken)
                                 : await ReihitsuFormatter.FormatNodeInDocumentWithContextAsync(document, target, FindDeclaration(root, contextName), TestContext.CancellationToken);

                await assert(document, result, endOfLine);
            }
        }
    }

    /// <summary>
    /// Asserts that a node-in-document entry point returns the input document itself
    /// </summary>
    /// <param name="source">The document source</param>
    /// <param name="targetName">The name of the target declaration</param>
    /// <param name="contextName">The name of the context declaration, or <see langword="null"/> for no context</param>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    private Task AssertNodeInDocumentReturnsDocumentUnchanged(string source, string targetName, string contextName)
    {
        return FormatNodeInDocument(source,
                                    targetName,
                                    contextName,
                                    (document, result, endOfLine) =>
                                    {
                                        Assert.AreSame(document, result, $"The document must be returned unchanged under {DescribeLineEnding(endOfLine)} line endings.");

                                        return Task.CompletedTask;
                                    });
    }

    /// <summary>
    /// Asserts the text a node-in-document entry point returns
    /// </summary>
    /// <param name="source">The document source</param>
    /// <param name="targetName">The name of the target declaration</param>
    /// <param name="contextName">The name of the context declaration, or <see langword="null"/> for no context</param>
    /// <param name="expected">The expected document text with LF line endings</param>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    private Task AssertNodeInDocumentText(string source, string targetName, string contextName, string expected)
    {
        return FormatNodeInDocument(source,
                                    targetName,
                                    contextName,
                                    async (_, result, endOfLine) =>
                                    {
                                        var text = (await result.GetTextAsync(TestContext.CancellationToken)).ToString();

                                        Assert.AreEqual(NormalizeLineEndings(expected, endOfLine), text, $"Document output mismatch under {DescribeLineEnding(endOfLine)} line endings.");
                                    });
    }

