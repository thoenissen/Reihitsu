    #region Methods

    /// <summary>
    /// Verifies the spec example: a statement without its semicolon is a syntax error, so the tree is returned unchanged
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-005")]
    public void FormatSyntaxTreeReturnsTreeWithMissingSemicolonUnchanged()
    {
        var tree = CSharpSyntaxTree.ParseText("class C{void M(){int x=1}}", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreSame(tree, result);
    }

    /// <summary>
    /// Verifies that an active <c>#error</c> directive is an error-level diagnostic, so the tree is returned unchanged
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-005")]
    public void FormatSyntaxTreeReturnsTreeWithActiveErrorDirectiveUnchanged()
    {
        var tree = CSharpSyntaxTree.ParseText("#error stop\nclass C{void M(){int x=1;}}", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreSame(tree, result);
    }

    /// <summary>
    /// Verifies the spec example: a generated-code marker inside the type does not disable formatting
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-006")]
    public void FormatSyntaxTreeFormatsFileWhoseMarkerIsInsideTheType()
    {
        const string input = """
                             class C{
                             // <auto-generated />
                             void M(){int x=1;}}
                             """;
        const string expected = """
                                class C
                                {
                                    // <auto-generated />
                                    void M()
                                    {
                                        int x = 1;
                                    }
                                }
                                """;

        foreach (var endOfLine in _lineEndings)
        {
            var tree = CSharpSyntaxTree.ParseText(NormalizeLineEndings(input, endOfLine), cancellationToken: TestContext.CancellationToken);

            var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

            Assert.AreEqual(NormalizeLineEndings(expected, endOfLine), result.ToString());
        }
    }

    /// <summary>
    /// Verifies that the marker is matched case-insensitively and without the hyphen in the header of the file
    /// </summary>
    /// <param name="header">The header comment</param>
    [TestMethod]
    [Requirement("FMT-PIPE-006")]
    [DataRow("// <AUTO-GENERATED />")]
    [DataRow("// <autogenerated />")]
    [DataRow("/* <AutoGenerated> */")]
    public void FormatSyntaxTreeReturnsFileWithHeaderMarkerUnchanged(string header)
    {
        var tree = CSharpSyntaxTree.ParseText($"{header}\nclass C{{void M(){{int x=1;}}}}", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreSame(tree, result);
    }

    /// <summary>
    /// Verifies that a marker in a comment after the first token does not disable formatting
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-006")]
    public void FormatSyntaxTreeFormatsFileWhoseMarkerFollowsTheFirstToken()
    {
        var tree = CSharpSyntaxTree.ParseText("using System; // <auto-generated />\nclass C{int x;}", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreEqual("using System; // <auto-generated />\nclass C\n{\n    int x;\n}", result.ToString());
    }

    /// <summary>
    /// Verifies the spec example: four <c>\r\n</c> line breaks against one <c>\n</c> make every line break <c>\r\n</c>
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-007")]
    public void FormatSyntaxTreeUsesThePredominantLineEnding()
    {
        var tree = CSharpSyntaxTree.ParseText("class C\r\n{\r\nvoid M(){}\r\n  int x;\n}\r\n", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreEqual("class C\r\n{\r\n    void M()\r\n    {\r\n    }\r\n    int x;\r\n}", result.ToString());
    }

    /// <summary>
    /// Verifies that a tie between <c>\r\n</c> and <c>\n</c> goes to <c>\r\n</c>
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-007")]
    public void FormatSyntaxTreeUsesCarriageReturnLineFeedOnTie()
    {
        var tree = CSharpSyntaxTree.ParseText("class C\r\n{\nint x;\r\n}\n", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreEqual("class C\r\n{\r\n    int x;\r\n}", result.ToString());
    }

    /// <summary>
    /// Verifies that documentation-comment newlines count towards the predominant line ending
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-007")]
    public void FormatSyntaxTreeCountsDocumentationNewlines()
    {
        var tree = CSharpSyntaxTree.ParseText("class C\n{\n    /// <summary>\r\n    /// Value.\r\n    /// </summary>\r\n    int A;\n}", cancellationToken: TestContext.CancellationToken);

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreEqual("class C\r\n{\r\n    /// <summary>\r\n    /// Value.\r\n    /// </summary>\r\n    int A;\r\n}", result.ToString());
    }

    /// <summary>
    /// Verifies that input without any line break is formatted with <see cref="Environment.NewLine"/>
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-007")]
    public void FormatSyntaxTreeFallsBackToEnvironmentNewLineWithoutLineBreaks()
    {
        var tree = CSharpSyntaxTree.ParseText("class C{int x;}", cancellationToken: TestContext.CancellationToken);
        var expected = string.Join(Environment.NewLine, "class C", "{", "    int x;", "}");

        var result = ReihitsuFormatter.FormatSyntaxTree(tree, TestContext.CancellationToken);

        Assert.AreEqual(expected, result.ToString());
    }

    /// <summary>
    /// Verifies that <see cref="ReihitsuFormatter.FormatDocumentAsync"/> and <see cref="ReihitsuFormatter.FormatSyntaxTree"/>
    /// produce the same text for the same input and language version
    /// </summary>
    /// <param name="languageVersion">The language version of the input</param>
    /// <returns>A <see cref="Task"/> representing the asynchronous unit test</returns>
    [TestMethod]
    [Requirement("FMT-PIPE-009")]
    [DataRow(LanguageVersion.CSharp5)]
    [DataRow(LanguageVersion.CSharp11)]
    [DataRow(LanguageVersion.Latest)]
    public async Task FormatDocumentAsyncAndFormatSyntaxTreeProduceTheSameText(LanguageVersion languageVersion)
    {
        const string input = """"
                             using System.Text;
                             using System;
                             namespace N{
                             class C{int P{get{return 1;}}
                             class Empty{}
                             void M(int x){if(x>0)Console.WriteLine(new StringBuilder());
                             var s="""
                                 raw
                                 """;}}}
                             """";
        var parseOptions = CSharpParseOptions.Default.WithLanguageVersion(languageVersion);

        foreach (var endOfLine in _lineEndings)
        {
            var source = NormalizeLineEndings(input, endOfLine);
            var treeText = ReihitsuFormatter.FormatSyntaxTree(CSharpSyntaxTree.ParseText(source, parseOptions, cancellationToken: TestContext.CancellationToken),
                                                              TestContext.CancellationToken)
                                            .ToString();

            using (var workspace = new AdhocWorkspace())
            {
                var project = workspace.AddProject("TestProject", LanguageNames.CSharp).WithParseOptions(parseOptions);
                var document = project.AddDocument("Test.cs", SourceText.From(source));

                var result = await ReihitsuFormatter.FormatDocumentAsync(document, TestContext.CancellationToken);
                var documentText = (await result.GetTextAsync(TestContext.CancellationToken)).ToString();

                Assert.AreNotEqual(source, treeText, "The input must be reformatted for the test to be meaningful.");
                Assert.AreEqual(treeText, documentText, $"Document and tree formatting differ under {DescribeLineEnding(endOfLine)} line endings.");
            }
        }
    }

    /// <summary>
    /// Verifies the spec example: only the target property is formatted and the following property is kept as written
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous unit test</returns>
    [TestMethod]
    [Requirement("FMT-PIPE-010")]
    [Requirement("FMT-PIPE-011")]
    public async Task FormatNodeInDocumentAsyncFormatsOnlyTheTargetProperty()
    {
        const string input = """
                             class C
                             {
                                 int P { get { return 1; } }
                                 int Q { get { return 2; } }
                             }
                             """;
        const string expected = """
                                class C
                                {
                                    int P
                                    {
                                        get
                                        {
                                            return 1;
                                        }
                                    }
                                    int Q { get { return 2; } }
                                }
                                """;

        foreach (var endOfLine in _lineEndings)
        {
            using (var workspace = new AdhocWorkspace())
            {
                var project = workspace.AddProject("TestProject", LanguageNames.CSharp);
                var document = project.AddDocument("Test.cs", SourceText.From(NormalizeLineEndings(input, endOfLine)));
                var root = await document.GetSyntaxRootAsync(TestContext.CancellationToken);
                var target = root?.DescendantNodes().OfType<PropertyDeclarationSyntax>().First();

                Assert.IsNotNull(target);

                var result = await ReihitsuFormatter.FormatNodeInDocumentAsync(document, target, TestContext.CancellationToken);
                var resultText = (await result.GetTextAsync(TestContext.CancellationToken)).ToString();

                Assert.AreEqual(NormalizeLineEndings(expected, endOfLine), resultText);
            }
        }
    }

    /// <summary>
    /// Verifies that the trailing trivia of the target, a trailing comment and the whitespace in front of it included, is kept
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous unit test</returns>
    [TestMethod]
    [Requirement("FMT-PIPE-010")]
    public async Task FormatNodeInDocumentAsyncKeepsTheTrailingTriviaOfTheTarget()
    {
        const string input = "class C\n{\n    void M()\n    {\n        var a=1;   // one\n        var b=2;\n    }\n}";
        const string expected = "class C\n{\n    void M()\n    {\n        var a = 1;   // one\n        var b=2;\n    }\n}";

        using (var workspace = new AdhocWorkspace())
        {
            var project = workspace.AddProject("TestProject", LanguageNames.CSharp);
            var document = project.AddDocument("Test.cs", SourceText.From(input));
            var root = await document.GetSyntaxRootAsync(TestContext.CancellationToken);
            var target = root?.DescendantNodes().OfType<LocalDeclarationStatementSyntax>().First();

            Assert.IsNotNull(target);

            var result = await ReihitsuFormatter.FormatNodeInDocumentAsync(document, target, TestContext.CancellationToken);
            var resultText = (await result.GetTextAsync(TestContext.CancellationToken)).ToString();

            Assert.AreEqual(expected, resultText);
        }
    }

    /// <summary>
    /// Verifies that <see cref="ReihitsuFormatter.FormatNode"/> formats a node of a tree that contains a syntax error elsewhere
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-012")]
    public void FormatNodeFormatsNodeOfTreeWithSyntaxErrors()
    {
        var tree = CSharpSyntaxTree.ParseText("class C\n{\n    void M(){int x=1}\n    void N(){int y=2;}\n}", cancellationToken: TestContext.CancellationToken);
        var target = tree.GetRoot(TestContext.CancellationToken).DescendantNodes().OfType<MethodDeclarationSyntax>().Last();

        Assert.Contains(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error, tree.GetDiagnostics(TestContext.CancellationToken));

        var result = ReihitsuFormatter.FormatNode(target, cancellationToken: TestContext.CancellationToken);

        Assert.AreEqual("    void N()\n    {\n        int y = 2;\n    }", result.ToFullString().TrimEnd('\n'));
    }

    /// <summary>
    /// Verifies that <see cref="ReihitsuFormatter.FormatNode"/> formats a node of a file that carries the generated-code marker
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-012")]
    public void FormatNodeFormatsNodeOfGeneratedFile()
    {
        var tree = CSharpSyntaxTree.ParseText("// <auto-generated />\nclass C\n{\n    void M(){int x=1;}\n}", cancellationToken: TestContext.CancellationToken);
        var target = tree.GetRoot(TestContext.CancellationToken).DescendantNodes().OfType<MethodDeclarationSyntax>().Single();

        var result = ReihitsuFormatter.FormatNode(target, cancellationToken: TestContext.CancellationToken);

        Assert.AreEqual("    void M()\n    {\n        int x = 1;\n    }", result.ToFullString().TrimEnd('\n'));
    }

    /// <summary>
    /// Verifies that a non-negative <c>indentLevel</c> sets the indentation instead of the node's position in its tree
    /// </summary>
    [TestMethod]
    [Requirement("FMT-PIPE-012")]
    public void FormatNodeTakesTheIndentationFromTheIndentLevelArgument()
    {
        var tree = CSharpSyntaxTree.ParseText("class C\n{\n    void M()\n    {\n        if(true){M();}\n    }\n}", cancellationToken: TestContext.CancellationToken);
        var target = tree.GetRoot(TestContext.CancellationToken).DescendantNodes().OfType<IfStatementSyntax>().Single();

        var atPosition = ReihitsuFormatter.FormatNode(target, cancellationToken: TestContext.CancellationToken);
        var atLevelOne = ReihitsuFormatter.FormatNode(target, indentLevel: 1, cancellationToken: TestContext.CancellationToken);

        Assert.AreEqual("        if (true)\n        {\n            M();\n        }", atPosition.ToFullString().TrimEnd('\n'));
        Assert.AreEqual("    if (true)\n    {\n        M();\n    }", atLevelOne.ToFullString().TrimEnd('\n'));
    }

    /// <summary>
    /// Verifies that <see cref="ReihitsuFormatter.FormatNode"/> removes the line breaks at the end of a node that is not part
    /// of a syntax tree
    /// </summary>
    [TestMethod]
    [Requirement("FMT-CLEAN-008")]
    public void FormatNodeRemovesTrailingLineBreaksOfDetachedNode()
    {
        foreach (var endOfLine in _lineEndings)
        {
            var node = SyntaxFactory.ParseMemberDeclaration(NormalizeLineEndings("void M(){int x=1;}\n\n", endOfLine));

            Assert.IsNotNull(node);

            var result = ReihitsuFormatter.FormatNode(node, indentLevel: 0, cancellationToken: TestContext.CancellationToken);

            Assert.AreEqual(NormalizeLineEndings("void M()\n{\n    int x = 1;\n}", endOfLine), result.ToFullString());
        }
    }

    #endregion // Methods
}