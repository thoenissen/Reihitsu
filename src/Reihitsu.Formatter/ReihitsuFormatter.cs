public static class ReihitsuFormatter
{
    #region Constants

    /// <summary>
    /// The configurable structural transforms the node-level entry points skip. Code fixes format the node they changed
    /// through those entry points, so a transform listed here would rewrite code the fix was not asked to change; document-level
    /// formatting runs every transform
    /// </summary>
    private const ConfigurableStructuralTransforms CodeFixDisabledStructuralTransforms = ConfigurableStructuralTransforms.AccessorExpressionBody;

    #endregion // Constants

    #region Methods

    /// <summary>
    /// Formats an entire document by applying all formatting rules.
    /// Version-dependent rules follow the language version of the document's parse options, clamped to the newest supported version
    /// </summary>
    /// <param name="document">The Roslyn Document to format</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// A result whose output is a new Document with formatting applied, or the document unchanged when the formatter refuses it
    /// as unsupported, which the result reports (FMT-UNSUP-001), or when it has a syntax error, is generated, or holds code that
    /// another build hides (FMT-PIPE-005, FMT-PIPE-006, FMT-PIPE-033), which the result does not report
    /// </returns>
    public static async Task<FormattingResult<Document>> FormatDocumentAsync(Document document, CancellationToken cancellationToken = default)
    {
        var syntaxTree = await document.GetSyntaxTreeAsync(cancellationToken).ConfigureAwait(false);

        if (syntaxTree == null)
        {
            return new FormattingResult<Document>(document, null);
        }

        var root = await syntaxTree.GetRootAsync(cancellationToken).ConfigureAwait(false);

        if (ReihitsuFormatterHelpers.HasSyntaxErrors(syntaxTree))
        {
            return new FormattingResult<Document>(document, null);
        }

        if (ReihitsuFormatterHelpers.IsAutoGeneratedSource(root)
            || ReihitsuFormatterHelpers.HoldsHidingCarrier(root))
        {
            return new FormattingResult<Document>(document, null);
        }

        var endOfLine = ReihitsuFormatterHelpers.DetectEndOfLine(root);
        var context = new FormattingContext(endOfLine, languageVersion: LanguageVersionResolver.Resolve(syntaxTree.Options));
        var result = FormattingPipeline.Execute(root, context, cancellationToken);

        return result.Unsupported != null
                   ? new FormattingResult<Document>(document, result.Unsupported)
                   : new FormattingResult<Document>(document.WithSyntaxRoot(result.Output), null);
    }

    /// <summary>
    /// Formats a syntax tree by applying all formatting rules.
    /// Use this overload when no Workspace/Document context is available.
    /// Version-dependent rules follow the language version of the tree's parse options, clamped to the newest supported version
    /// </summary>
    /// <param name="syntaxTree">The syntax tree to format</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// A result whose output is a new SyntaxTree with formatting applied, or the tree unchanged when the formatter refuses it as
    /// unsupported, which the result reports (FMT-UNSUP-001), or when it has a syntax error, is generated, or holds code that
    /// another build hides (FMT-PIPE-005, FMT-PIPE-006, FMT-PIPE-033), which the result does not report
    /// </returns>
    public static FormattingResult<SyntaxTree> FormatSyntaxTree(SyntaxTree syntaxTree, CancellationToken cancellationToken = default)
    {
        if (ReihitsuFormatterHelpers.HasSyntaxErrors(syntaxTree))
        {
            return new FormattingResult<SyntaxTree>(syntaxTree, null);
        }

        var root = syntaxTree.GetRoot(cancellationToken);

        if (ReihitsuFormatterHelpers.IsAutoGeneratedSource(root)
            || ReihitsuFormatterHelpers.HoldsHidingCarrier(root))
        {
            return new FormattingResult<SyntaxTree>(syntaxTree, null);
        }

        var endOfLine = ReihitsuFormatterHelpers.DetectEndOfLine(root);
        var context = new FormattingContext(endOfLine, languageVersion: LanguageVersionResolver.Resolve(syntaxTree.Options));
        var result = FormattingPipeline.Execute(root, context, cancellationToken);

        return result.Unsupported != null
                   ? new FormattingResult<SyntaxTree>(syntaxTree, result.Unsupported)
                   : new FormattingResult<SyntaxTree>(syntaxTree.WithRootAndOptions(result.Output, syntaxTree.Options), null);
    }

    /// <summary>
    /// Formats a specific syntax node and its descendants.
    /// Useful for code fix providers that need to format only a
    /// newly generated or modified node rather than the full document
    /// </summary>
    /// <param name="node">The syntax node to format</param>
    /// <param name="indentLevel">
    /// The indentation level of the node within its containing document. When it is negative, the node is laid out at the
    /// depth the indentation phase gives its first token at its position in its tree, which is 0 for a node without a parent
    /// </param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// A result whose output is a new SyntaxNode with formatting applied, or the node unchanged when the formatter refuses it as
    /// unsupported, which the result reports with a location in the node's syntax tree (FMT-UNSUP-001, FMT-UNSUP-002)
    /// </returns>
    /// <remarks>
    /// Unlike the document- and tree-level entry points, this overload intentionally omits the
    /// syntax-error and auto-generated guards. It operates on a caller-supplied node — typically a
    /// freshly generated or detached subtree produced by a code fix — that has no file header to
    /// inspect and is not expected to carry whole-file error diagnostics. Callers are responsible for
    /// passing a node that is safe to format. Like every node-level entry point, it keeps single-statement
    /// accessor blocks instead of converting them to expression bodies, and keeps the accessor list of get-only
    /// properties and indexers instead of converting them to expression-bodied members, and applies no region requirement
    /// (FMT-PIPE-028). Version-dependent rules follow the language version
    /// of the tree that Roslyn reports as the node's syntax tree, whether or not the node has a parent; a node that reports a tree
    /// with the default parse options is formatted for the newest supported version. A node that is part of a tree is formatted as
    /// a root without a parent: the code in front of it and behind it, and the construct it stands in, are not read, so it gets the
    /// result the same node without a parent gets at the same depth, and its caller decides what stands around the result
    /// </remarks>
    public static FormattingResult<SyntaxNode> FormatNode(SyntaxNode node, int indentLevel = -1, CancellationToken cancellationToken = default)
    {
        var endOfLine = ReihitsuFormatterHelpers.DetectEndOfLine(node);
        var baseIndentLevel = indentLevel >= 0 ? indentLevel : SyntaxIndentationUtilities.ComputeIndentLevel(node);
        var context = new FormattingContext(endOfLine,
                                            baseIndentLevel,
                                            preserveRootDocumentationBoundary: node is not CompilationUnitSyntax,
                                            disabledStructuralTransforms: CodeFixDisabledStructuralTransforms,
                                            languageVersion: LanguageVersionResolver.Resolve(node.SyntaxTree.Options),
                                            formatsRegionDirectives: false);

        var detachedNode = ReihitsuFormatterHelpers.Detach(node, cancellationToken);
        var result = FormattingPipeline.Execute(detachedNode, context, cancellationToken);

        return result.Unsupported != null
                   ? new FormattingResult<SyntaxNode>(node, MapToCallerTree(result.Unsupported, detachedNode, node))
                   : result;
    }

    /// <summary>
    /// Formats a specific syntax node using document-derived indentation and line-ending context.
    /// Only the targeted node is rewritten back into the document; callers that intend document-wide
    /// formatting should use <see cref="FormatDocumentAsync(Document, CancellationToken)"/> instead
    /// </summary>
    /// <param name="document">The Roslyn Document containing the target node</param>
    /// <param name="targetNode">The syntax node to format. Must belong to the document's syntax tree</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// A result whose output is a new Document with only the targeted node formatted, or the document unchanged when the
    /// formatter refuses the target as unsupported, which the result reports (FMT-UNSUP-001, FMT-UNSUP-002)
    /// </returns>
    /// <remarks>
    /// Single-statement accessor blocks inside the target are kept rather than converted to expression bodies, and
    /// get-only properties and indexers keep their accessor list rather than becoming expression-bodied members,
    /// including when the target is the document root, because this entry point serves code fixes; for the same reason, it
    /// applies no region requirement (FMT-PIPE-028).
    /// Version-dependent rules follow the effective language version of the document's project, clamped to the newest
    /// supported version. The target is formatted as a root without a parent; what the phases need from the document around it
    /// is captured before they run, as plain values: its depth, the column of its first token, and the construct it stands in.
    /// The target's leading trivia is written back as it stands in the document, in every case — its blank lines, its comments
    /// and documentation comments, and the whitespace in front of its first token — so that token keeps its line and column, and
    /// the target's other lines are laid out from that column (FMT-PIPE-017, FMT-PIPE-018).
    /// The target's trailing trivia is kept, but the line break that ends it is written in the detected line ending and the
    /// whitespace in front of that line break is removed, as on every other line of the target (FMT-PIPE-010)
    /// </remarks>
    public static async Task<FormattingResult<Document>> FormatNodeInDocumentAsync(Document document, SyntaxNode targetNode, CancellationToken cancellationToken = default)
    {
        var syntaxTree = await document.GetSyntaxTreeAsync(cancellationToken).ConfigureAwait(false);

        if (syntaxTree == null)
        {
            return new FormattingResult<Document>(document, null);
        }

        var root = await syntaxTree.GetRootAsync(cancellationToken).ConfigureAwait(false);

        // The generated-code marker is not checked: a code fix runs only where an analyzer reported, so the analyzers'
        // decision on generated code governs (FMT-PIPE-006)
        if (ReihitsuFormatterHelpers.HasSyntaxErrors(syntaxTree))
        {
            return new FormattingResult<Document>(document, null);
        }

        var originalFirstToken = targetNode.GetFirstToken();

        // The target's leading trivia is written back as it stands in the document, so every character in front of its first
        // token is kept, and the indentation phase lays out the target so that the token keeps its column there; no line is
        // moved after the last phase (FMT-PIPE-017, FMT-PIPE-018)
        int? rootFirstTokenColumn = targetNode == root
                                        ? null
                                        : ReihitsuFormatterHelpers.ComputeDocumentColumn(originalFirstToken);
        var endOfLine = ReihitsuFormatterHelpers.DetectEndOfLine(root);
        var baseIndentLevel = SyntaxIndentationUtilities.ComputeIndentLevel(targetNode);
        var context = new FormattingContext(endOfLine,
                                            baseIndentLevel,
                                            preserveRootDocumentationBoundary: targetNode != root,
                                            disabledStructuralTransforms: CodeFixDisabledStructuralTransforms,
                                            languageVersion: LanguageVersionResolver.Resolve(document.Project.ParseOptions),
                                            rootFirstTokenColumn: rootFirstTokenColumn,
                                            rootChainBoundary: FluentChainBoundary.From(targetNode),
                                            rootConstruct: ReihitsuFormatterHelpers.CaptureRootConstruct(targetNode),
                                            formatsRegionDirectives: false);
        var lastTokenAnnotation = new SyntaxAnnotation();
        var detachedTarget = DetachWithAnnotatedLastToken(targetNode, targetNode == root ? null : lastTokenAnnotation, cancellationToken);
        var result = FormattingPipeline.Execute(detachedTarget, context, cancellationToken);

        if (result.Unsupported != null)
        {
            return new FormattingResult<Document>(document, MapToCallerTree(result.Unsupported, detachedTarget, targetNode));
        }

        var formattedTarget = result.Output;

        if (targetNode == root)
        {
            return new FormattingResult<Document>(document.WithSyntaxRoot(formattedTarget), null);
        }

        // The target's leading trivia is written back as it stands in the document, in every case: its blank lines, its
        // comments and documentation comments in their text and columns, and the whitespace in front of its first token
        // (FMT-PIPE-018)
        var formattedFirstToken = formattedTarget.GetFirstToken();

        formattedTarget = formattedTarget.ReplaceToken(formattedFirstToken, formattedFirstToken.WithLeadingTrivia(originalFirstToken.LeadingTrivia));
        formattedTarget = WriteBackTrailingTrivia(formattedTarget, targetNode.GetLastToken(), lastTokenAnnotation, endOfLine);

        return new FormattingResult<Document>(document.WithSyntaxRoot(root.ReplaceNode(targetNode, formattedTarget)), null);
    }

    /// <summary>
    /// Formats a target node using a containing node for positional context, then rewrites only the
    /// target node back into the document. This is useful when the formatter phases need the code of the
    /// context around the target to lay the target out
    /// </summary>
    /// <param name="document">The Roslyn Document containing both nodes</param>
    /// <param name="targetNode">The syntax node whose formatted result should be applied</param>
    /// <param name="contextNode">A containing syntax node used while formatting the target</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// A result whose output is a new Document with only the targeted node formatted, or the document unchanged when the
    /// formatter refuses the context as unsupported, which the result reports (FMT-UNSUP-001, FMT-UNSUP-002)
    /// </returns>
    /// <remarks>
    /// Single-statement accessor blocks are kept rather than converted to expression bodies, and get-only properties
    /// and indexers keep their accessor list rather than becoming expression-bodied members, because this entry point
    /// serves code fixes; for the same reason, no region requirement is applied (FMT-PIPE-028). Version-dependent rules
    /// follow the effective language version of the document's project, clamped to the newest supported version. The
    /// target's leading trivia is written back as it stands in the document, and everything in front of the target on
    /// its line stays as it is, so the target's first token keeps its line and its column in the document, also where
    /// the context's layout would put it on another line or in another column; the target's other lines are laid out
    /// as the formatter lays them out from that column, so a line aligned to an anchor on the target's first line stays
    /// on that anchor (FMT-PIPE-017, FMT-PIPE-018). A target that the structural phase splits into several fields is
    /// replaced by all of them, laid out as the phases lay them out, and no field shares a line with another member
    /// (FMT-PIPE-029). The target's trailing trivia is kept, but the line break that ends it is written in the detected
    /// line ending and the whitespace in front of that line break is removed, as on every other line of the target
    /// (FMT-PIPE-010). The generated-code marker is not checked (FMT-PIPE-006). When the target is the context node,
    /// formatting is delegated to
    /// <see cref="FormatNodeInDocumentAsync(Document, SyntaxNode, CancellationToken)"/>
    /// </remarks>
    public static async Task<FormattingResult<Document>> FormatNodeInDocumentWithContextAsync(Document document,
                                                                                              SyntaxNode targetNode,
                                                                                              SyntaxNode contextNode,
                                                                                              CancellationToken cancellationToken = default)
    {
        if (targetNode == contextNode)
        {
            return await FormatNodeInDocumentAsync(document, targetNode, cancellationToken).ConfigureAwait(false);
        }

        var syntaxTree = await document.GetSyntaxTreeAsync(cancellationToken).ConfigureAwait(false);

        if (syntaxTree == null
            || targetNode.SyntaxTree != syntaxTree
            || contextNode.SyntaxTree != syntaxTree
            || contextNode.FullSpan.Contains(targetNode.FullSpan) == false)
        {
            return new FormattingResult<Document>(document, null);
        }

        var root = await syntaxTree.GetRootAsync(cancellationToken).ConfigureAwait(false);

        // The generated-code marker is not checked, as in FormatNodeInDocumentAsync (FMT-PIPE-006)
        if (ReihitsuFormatterHelpers.HasSyntaxErrors(syntaxTree))
        {
            return new FormattingResult<Document>(document, null);
        }

        if (targetNode is FieldDeclarationSyntax fieldDeclaration
            && SplitsFieldDeclaration(fieldDeclaration))
        {
            return FormatSplitFieldInContext(document, root, fieldDeclaration, contextNode, cancellationToken);
        }

        var targetTokenAnnotation = new SyntaxAnnotation();
        var originalFirstToken = targetNode.GetFirstToken();

        // Everything in front of the target's first token is kept as it stands in the document, because only the target
        // is written back, so that token keeps its line and its column there, and the indentation phase lays out the
        // target's other lines from that column, wherever the phases leave the token in the context (FMT-PIPE-017,
        // FMT-PIPE-024)
        var contextResult = FormatContext(document,
                                          root,
                                          targetNode,
                                          contextNode,
                                          ReihitsuFormatterHelpers.ComputeDocumentColumn(originalFirstToken),
                                          targetTokenAnnotation,
                                          targetNodeAnnotation: null,
                                          cancellationToken);

        if (contextResult.Unsupported != null)
        {
            return new FormattingResult<Document>(document, contextResult.Unsupported);
        }

        var formattedTarget = FindCorrespondingNode(targetNode, contextResult.Output, targetTokenAnnotation);

        if (formattedTarget == null)
        {
            return new FormattingResult<Document>(document, null);
        }

        // The target's leading trivia is written back as it stands in the document, in every case: its blank lines, its
        // comments and directives in their columns, and the whitespace in front of its first token (FMT-PIPE-018). The
        // target's first token therefore stays where the document has it, the column its other lines were laid out from
        var formattedFirstToken = formattedTarget.GetFirstToken();
        var updatedFirstToken = formattedFirstToken.WithLeadingTrivia(originalFirstToken.LeadingTrivia)
                                                   .WithoutAnnotations(targetTokenAnnotation);

        formattedTarget = formattedTarget.ReplaceToken(formattedFirstToken, updatedFirstToken);

        var originalLastToken = targetNode.GetLastToken();
        var formattedLastToken = formattedTarget.GetLastToken();
        var trailingTrivia = TargetWriteBackUtilities.EndTargetLineAsFormatted(originalLastToken.TrailingTrivia, ReihitsuFormatterHelpers.DetectEndOfLine(root));

        formattedTarget = formattedTarget.ReplaceToken(formattedLastToken, formattedLastToken.WithTrailingTrivia(trailingTrivia));

        return new FormattingResult<Document>(document.WithSyntaxRoot(root.ReplaceNode(targetNode, formattedTarget)), null);
    }

    /// <summary>
    /// Rewrites the using block of one scope of a document as the using-directive phase rewrites it, and nothing else of the
    /// document (FMT-PIPE-030). The phase reads the scope where it stands in the document and is the only phase that runs, so
    /// its output, the scope's indentation in front of a directive it moves onto a line of its own included, is the block's
    /// final layout
    /// </summary>
    /// <param name="document">The Roslyn Document containing the scope</param>
    /// <param name="scope">The compilation unit, namespace, or file-scoped namespace whose using block is organized. Must belong to the document's syntax tree</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>A new Document with the scope's using block organized, or the unchanged document when the block does not change</returns>
    /// <remarks>
    /// Neither syntax errors (FMT-PIPE-005) nor the generated-code marker (FMT-PIPE-006) are checked. The directives of a
    /// namespace nested in the scope are not changed
    /// </remarks>
    public static async Task<Document> OrganizeUsingDirectivesInDocumentAsync(Document document, SyntaxNode scope, CancellationToken cancellationToken = default)
    {
        var root = await document.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);

        if (root == null
            || scope.SyntaxTree != root.SyntaxTree)
        {
            return document;
        }

        var usingDirectives = UsingDirectiveOrderingUtilities.GetUsings(scope);
        var context = new FormattingContext(ReihitsuFormatterHelpers.DetectEndOfLine(root),
                                            languageVersion: LanguageVersionResolver.Resolve(document.Project.ParseOptions));
        var organizedScope = new UsingDirectiveOrderingPhase().Execute(scope, context, cancellationToken);
        var organizedUsings = UsingDirectiveOrderingUtilities.GetUsings(organizedScope);

        if (organizedUsings.SequenceEqual(usingDirectives))
        {
            return document;
        }

        return document.WithSyntaxRoot(root.ReplaceNode(scope, UsingDirectiveOrderingUtilities.WithUsings(scope, organizedUsings)));
    }

    /// <summary>
    /// Lays out one element of a single-line documentation comment as the documentation-comment phase lays it out, and
    /// nothing else of the document (FMT-PIPE-032). The element is laid out where it stands in the document: every line it
    /// gains starts with the indentation in front of the <c>///</c> on the line of its start tag and ends with the
    /// document's line ending, so the phase's output is the element's final text
    /// </summary>
    /// <param name="document">The Roslyn Document containing the element</param>
    /// <param name="element">The element, closed by an end tag of its own, in a <c>///</c> comment that starts its own line. Must belong to the document's syntax tree</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>A new Document with the element laid out, or the unchanged document when the element is already in a canonical shape</returns>
    /// <remarks>
    /// Neither syntax errors (FMT-PIPE-005) nor the generated-code marker (FMT-PIPE-006) are checked, and no input is
    /// refused as unsupported (FMT-UNSUP-002)
    /// </remarks>
    public static async Task<Document> FormatDocumentationElementInDocumentAsync(Document document, XmlElementSyntax element, CancellationToken cancellationToken = default)
    {
        var root = await document.GetSyntaxRootAsync(cancellationToken).ConfigureAwait(false);

        if (root == null
            || element.SyntaxTree != root.SyntaxTree)
        {
            return document;
        }

        var syntaxTree = DocumentationCommentFormattingPhase.LayOutElement(root.SyntaxTree, element, ReihitsuFormatterHelpers.DetectEndOfLine(root), cancellationToken);

        return ReferenceEquals(syntaxTree, root.SyntaxTree)
                   ? document
                   : document.WithText(await syntaxTree.GetTextAsync(cancellationToken).ConfigureAwait(false));
    }

    /// <summary>
    /// Determines whether the structural phase splits the field declaration into one declaration per declarator: it has more
    /// than one declarator, is a member of a class, struct, record, interface, or union, has no disabled text in its leading
    /// trivia, and has no documentation comment (FMT-STRUCT-022, FMT-STRUCT-030, FMT-PIPE-031). Whether the formatter refuses
    /// the declaration as unsupported is not part of the answer; <see cref="FindUnsupportedSyntax"/> answers that
    /// </summary>
    /// <param name="fieldDeclaration">The field declaration</param>
    /// <returns><see langword="true"/> if the formatter splits the declaration; otherwise, <see langword="false"/></returns>
    public static bool SplitsFieldDeclaration(FieldDeclarationSyntax fieldDeclaration)
    {
        return FieldDeclarationSplitTransform.Splits(fieldDeclaration);
    }

    /// <summary>
    /// Determines whether the tree holds a hiding carrier (FMT-PIPE-033): a multi-line string literal or delimited comment that
    /// starts inside a conditional group and holds a line another build reads as an <c>#elif</c>, <c>#else</c>, or <c>#endif</c>
    /// directive. Whole-document formatting leaves such a tree unchanged; a code fix asks it when it registers, about every
    /// document it changes (SHARED-FIX-012), and the command-line tool and the playground ask it to name such a file as skipped
    /// </summary>
    /// <param name="syntaxTree">The syntax tree</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns><see langword="true"/> if the tree holds a hiding carrier; otherwise, <see langword="false"/></returns>
    public static bool HoldsHidingCarrier(SyntaxTree syntaxTree, CancellationToken cancellationToken = default)
    {
        return ReihitsuFormatterHelpers.HoldsHidingCarrier(syntaxTree.GetRoot(cancellationToken));
    }

    /// <summary>
    /// Finds the shape for which the formatter refuses the node as the input of its phases, by the precheck's own predicate,
    /// without formatting the node; text outside the node does not decide it (FMT-UNSUP-003, FMT-UNSUP-007). A code fix asks
    /// it when it registers, about exactly the node or context it formats (SHARED-FIX-010)
    /// </summary>
    /// <param name="node">The node the formatter would receive</param>
    /// <returns>The unsupported shape that starts first in the node's text, with its location in the node's syntax tree, or <see langword="null"/> when the formatter does not refuse the node</returns>
    public static UnsupportedSyntax FindUnsupportedSyntax(SyntaxNode node)
    {
        return PrecheckPhase.FindUnsupportedSyntax(node);
    }

    /// <summary>
    /// Moves the location of a shape the pipeline found in the copy of a node it received to the same text in the caller's
    /// syntax tree. The copy is the node detached as the root of a tree of its own, so it has the node's text from position 0
    /// </summary>
    /// <param name="unsupported">The shape, located in the copy</param>
    /// <param name="phaseInput">The copy the pipeline received</param>
    /// <param name="callerNode">The node in the caller's syntax tree</param>
    /// <returns>The shape, located in the caller's syntax tree</returns>
    private static UnsupportedSyntax MapToCallerTree(UnsupportedSyntax unsupported, SyntaxNode phaseInput, SyntaxNode callerNode)
    {
        if (phaseInput.SyntaxTree == callerNode.SyntaxTree)
        {
            return unsupported;
        }

        var span = unsupported.Location.SourceSpan;
        var offset = callerNode.FullSpan.Start - phaseInput.FullSpan.Start;

        return new UnsupportedSyntax(unsupported.Reason, Location.Create(callerNode.SyntaxTree, new TextSpan(span.Start + offset, span.Length)));
    }

    /// <summary>
    /// Detaches a node-level formatting target from its document as the root of a tree of its own, and marks its last token
    /// so that <see cref="WriteBackTrailingTrivia"/> can find that token where the phases leave it
    /// </summary>
    /// <param name="targetNode">The target node</param>
    /// <param name="lastTokenAnnotation">The annotation for the target's last token, or <see langword="null"/> to mark nothing</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>The detached target</returns>
    private static SyntaxNode DetachWithAnnotatedLastToken(SyntaxNode targetNode, SyntaxAnnotation lastTokenAnnotation, CancellationToken cancellationToken)
    {
        var detachedTarget = ReihitsuFormatterHelpers.Detach(targetNode, cancellationToken);

        if (lastTokenAnnotation == null)
        {
            return detachedTarget;
        }

        var lastToken = detachedTarget.GetLastToken();
        var annotatedTarget = detachedTarget.ReplaceToken(lastToken, lastToken.WithAdditionalAnnotations(lastTokenAnnotation));

        return detachedTarget.SyntaxTree.WithRootAndOptions(annotatedTarget, detachedTarget.SyntaxTree.Options).GetRoot(cancellationToken);
    }

    /// <summary>
    /// Writes the target's trailing trivia back behind the formatted target's last token, which lost it when the target was
    /// formatted as a root of its own (FMT-PIPE-010). The trivia is the author's text behind the target, so each comment in it
    /// is written once: when the phases leave the target's original last token inside the result, behind which they inserted
    /// tokens such as the closing brace of a block wrapped around a body (FMT-STRUCT-001), the comments that token still
    /// carries stay where they are, and only the rest of the trivia, the line break that keeps the code behind the target on
    /// its line among it, is written behind the result's last token, with the line that trivia ends ended as the phases end
    /// every other line of the target. The mark on the original last token is removed
    /// </summary>
    /// <param name="formattedTarget">The formatted target</param>
    /// <param name="originalLastToken">The target's last token as it stands in the document</param>
    /// <param name="lastTokenAnnotation">The annotation that marks the original last token in <paramref name="formattedTarget"/></param>
    /// <param name="endOfLine">The line ending detected for the document</param>
    /// <returns>The formatted target with the trailing trivia written back</returns>
    private static SyntaxNode WriteBackTrailingTrivia(SyntaxNode formattedTarget, SyntaxToken originalLastToken, SyntaxAnnotation lastTokenAnnotation, string endOfLine)
    {
        var formattedLastToken = formattedTarget.GetLastToken();
        var markedTokens = formattedTarget.GetAnnotatedTokens(lastTokenAnnotation).ToList();
        var trailingTrivia = originalLastToken.TrailingTrivia;

        if (formattedLastToken.HasAnnotation(lastTokenAnnotation) == false)
        {
            var keptCommentCount = markedTokens.Sum(static token => token.TrailingTrivia.Count(SyntaxTriviaUtilities.IsCommentTrivia));

            trailingTrivia = RemoveLeadingComments(trailingTrivia, keptCommentCount);
        }

        trailingTrivia = TargetWriteBackUtilities.EndTargetLineAsFormatted(trailingTrivia, endOfLine);

        return formattedTarget.ReplaceTokens(markedTokens.Append(formattedLastToken).Distinct(),
                                             (original, rewritten) =>
                                             {
                                                 var unmarkedToken = rewritten.WithoutAnnotations(lastTokenAnnotation);

                                                 return original == formattedLastToken
                                                            ? unmarkedToken.WithTrailingTrivia(trailingTrivia)
                                                            : unmarkedToken;
                                             });
    }

    /// <summary>
    /// Removes the first comments of a trivia list, each together with the whitespace in front of it
    /// </summary>
    /// <param name="trivia">The trivia list</param>
    /// <param name="commentCount">The number of comments to remove</param>
    /// <returns>The trivia list without those comments</returns>
    private static SyntaxTriviaList RemoveLeadingComments(SyntaxTriviaList trivia, int commentCount)
    {
        if (commentCount == 0)
        {
            return trivia;
        }

        var remainingTrivia = new List<SyntaxTrivia>(trivia.Count);
        var removedCount = 0;

        foreach (var item in trivia)
        {
            if (removedCount < commentCount
                && SyntaxTriviaUtilities.IsCommentTrivia(item))
            {
                while (remainingTrivia.Count > 0
                       && remainingTrivia[remainingTrivia.Count - 1].IsKind(SyntaxKind.WhitespaceTrivia))
                {
                    remainingTrivia.RemoveAt(remainingTrivia.Count - 1);
                }

                removedCount++;

                continue;
            }

            remainingTrivia.Add(item);
        }

        return SyntaxFactory.TriviaList(remainingTrivia);
    }

    /// <summary>
    /// Runs the pipeline on a copy of the context in which the target is marked, with the facts the context entry point gives
    /// the phases: the document column of the context's first token, the code-fix structural transforms, the project's
    /// language version, no region requirement, and the target-position fact (FMT-PIPE-017, FMT-PIPE-024, FMT-PIPE-028)
    /// </summary>
    /// <param name="document">The Roslyn Document containing both nodes</param>
    /// <param name="root">The document's root</param>
    /// <param name="targetNode">The target node, contained in the context</param>
    /// <param name="contextNode">The containing node that is formatted</param>
    /// <param name="targetFirstTokenColumn">The column the indentation phase lays out the target's other lines from, or <see langword="null"/> when the target's lines are laid out as the phases place them</param>
    /// <param name="targetTokenAnnotation">The annotation that marks the target's first token</param>
    /// <param name="targetNodeAnnotation">An annotation that marks the target node, or <see langword="null"/></param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// The formatted copy of the context, or the copy unchanged with the unsupported shape the context is refused for, located in
    /// the document's syntax tree (FMT-UNSUP-002)
    /// </returns>
    private static FormattingResult<SyntaxNode> FormatContext(Document document,
                                                              SyntaxNode root,
                                                              SyntaxNode targetNode,
                                                              SyntaxNode contextNode,
                                                              int? targetFirstTokenColumn,
                                                              SyntaxAnnotation targetTokenAnnotation,
                                                              SyntaxAnnotation targetNodeAnnotation,
                                                              CancellationToken cancellationToken)
    {
        // Only the target is written back, and its leading trivia as it stands in the document (FMT-PIPE-018), so the
        // whitespace in front of the context's first token is never rewritten and each of its characters counts as one
        // column; the indentation phase keeps that token in its column (FMT-PIPE-017)
        int? rootFirstTokenColumn = contextNode == root
                                        ? null
                                        : ReihitsuFormatterHelpers.ComputeDocumentColumn(contextNode.GetFirstToken());
        var context = new FormattingContext(ReihitsuFormatterHelpers.DetectEndOfLine(root),
                                            SyntaxIndentationUtilities.ComputeIndentLevel(contextNode),
                                            preserveRootDocumentationBoundary: contextNode != root,
                                            disabledStructuralTransforms: CodeFixDisabledStructuralTransforms,
                                            languageVersion: LanguageVersionResolver.Resolve(document.Project.ParseOptions),
                                            rootFirstTokenColumn: rootFirstTokenColumn,
                                            formatsRegionDirectives: false,
                                            targetAnnotation: targetTokenAnnotation,
                                            targetFirstTokenColumn: targetFirstTokenColumn);
        var originalFirstToken = targetNode.GetFirstToken();
        var annotatedTarget = targetNode.ReplaceToken(originalFirstToken, originalFirstToken.WithAdditionalAnnotations(targetTokenAnnotation));

        if (targetNodeAnnotation != null)
        {
            annotatedTarget = annotatedTarget.WithAdditionalAnnotations(targetNodeAnnotation);
        }

        // The copy of the context is the root of a tree of its own, so no phase reaches the code around it (FMT-PIPE-023)
        var contextCopy = contextNode.ReplaceNode(targetNode, annotatedTarget);
        var result = FormattingPipeline.Execute(contextCopy, context, cancellationToken);

        return result.Unsupported != null
                   ? new FormattingResult<SyntaxNode>(contextCopy, MapToCallerTree(result.Unsupported, contextCopy, contextNode))
                   : result;
    }

    /// <summary>
    /// Formats the type that declares a field declaration the structural phase splits, and writes back in place of the
    /// declaration every field the split makes of it, and nothing else of the context (FMT-PIPE-029)
    /// </summary>
    /// <param name="document">The Roslyn Document containing both nodes</param>
    /// <param name="root">The document's root</param>
    /// <param name="targetField">The field declaration the split splits</param>
    /// <param name="contextNode">A containing syntax node used while formatting the target</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>
    /// A result whose output is a new Document with the split fields written back, or the unchanged document when the fields
    /// cannot be found or the formatter refuses the context as unsupported, which the result reports (FMT-UNSUP-002)
    /// </returns>
    /// <remarks>
    /// The first field keeps the target's leading trivia, and its first token the line and column the target's first token
    /// has in the document (FMT-PIPE-017, FMT-PIPE-018); the last keeps the target's trailing trivia, with the line it ends
    /// ended as the phases end every other line (FMT-PIPE-010); every
    /// other line of the fields is the phases' layout. When another member of the type shares the target's first or last line,
    /// which is read from the context as the phases lay it out and asked only where nothing in the gap starts a line in the
    /// document, the whitespace in that gap is replaced by one line break and the indentation the phases give a later field,
    /// so no field shares a line with another member; a comment in the trailing trivia in front of the gap stays behind its
    /// token, and the leading trivia behind the gap, a documentation comment included, goes with its member onto the next line
    /// </remarks>
    private static FormattingResult<Document> FormatSplitFieldInContext(Document document,
                                                                        SyntaxNode root,
                                                                        FieldDeclarationSyntax targetField,
                                                                        SyntaxNode contextNode,
                                                                        CancellationToken cancellationToken)
    {
        // SplitsFieldDeclaration admits only a member of a class, struct, record, interface, or union
        var declaringType = (TypeDeclarationSyntax)targetField.Parent;
        var members = declaringType.Members;
        var targetIndex = members.IndexOf(targetField);
        var originalFirstToken = targetField.GetFirstToken();
        var originalLastToken = targetField.GetLastToken();

        var targetTokenAnnotation = new SyntaxAnnotation();
        var targetFieldAnnotation = new SyntaxAnnotation();

        // Whether another member shares the target's first or last line is a question only where nothing in the gap starts a
        // line in the document; where something does, the gap's trivia stays as it stands (FMT-PIPE-010, FMT-PIPE-018)
        var mayShareLineWithPrecedingMember = targetIndex > 0
                                              && SyntaxTriviaUtilities.AreSeparatedByEndOfLine(SyntaxTokenNavigationUtilities.GetPreviousToken(originalFirstToken), originalFirstToken) == false;
        var mayShareLineWithFollowingMember = targetIndex < members.Count - 1
                                              && SyntaxTriviaUtilities.AreSeparatedByEndOfLine(originalLastToken, SyntaxTokenNavigationUtilities.GetNextToken(originalLastToken)) == false;

        // A first field that keeps the target's line keeps its first token's document column, and the indentation phase lays
        // out its other lines from that column (FMT-PIPE-017). A first field that starts the next line, behind another member,
        // stands where the phases place a member, so its lines are laid out as the phases place them. Which of the two applies
        // is the phases' result, so a context laid out for the one the result does not confirm is laid out again for the
        // other; the column is read only by the indentation phase, so the second layout starts the same lines
        var documentColumn = ReihitsuFormatterHelpers.ComputeDocumentColumn(originalFirstToken);

        // The split builds every field from the target, so each field it makes carries the target's annotation, and the
        // first of them the annotated first token, which the target-position fact marks (FMT-PIPE-024)
        var contextResult = FormatContext(document,
                                          root,
                                          targetField,
                                          contextNode,
                                          mayShareLineWithPrecedingMember ? null : documentColumn,
                                          targetTokenAnnotation,
                                          targetFieldAnnotation,
                                          cancellationToken);

        if (contextResult.Unsupported != null)
        {
            return new FormattingResult<Document>(document, contextResult.Unsupported);
        }

        if (TargetWriteBackUtilities.TryGetSplitFields(contextResult.Output, targetField, targetFieldAnnotation, out var formattedFields) == false)
        {
            return new FormattingResult<Document>(document, null);
        }

        var sharesLineWithPrecedingMember = mayShareLineWithPrecedingMember
                                            && TargetWriteBackUtilities.StartsLineInLayout(formattedFields[0].GetFirstToken());

        if (mayShareLineWithPrecedingMember
            && sharesLineWithPrecedingMember == false)
        {
            // The context is the same as in the first layout, which the formatter did not refuse
            var secondContextResult = FormatContext(document,
                                                    root,
                                                    targetField,
                                                    contextNode,
                                                    documentColumn,
                                                    targetTokenAnnotation,
                                                    targetFieldAnnotation,
                                                    cancellationToken);

            if (TargetWriteBackUtilities.TryGetSplitFields(secondContextResult.Output, targetField, targetFieldAnnotation, out formattedFields) == false)
            {
                return new FormattingResult<Document>(document, null);
            }
        }

        var sharesLineWithFollowingMember = mayShareLineWithFollowingMember
                                            && TargetWriteBackUtilities.StartsLineInLayout(SyntaxTokenNavigationUtilities.GetNextToken(formattedFields[formattedFields.Count - 1].GetLastToken()));

        var updatedMembers = TargetWriteBackUtilities.ReplaceTargetBySplitFields(members,
                                                                                 targetIndex,
                                                                                 formattedFields,
                                                                                 sharesLineWithPrecedingMember,
                                                                                 sharesLineWithFollowingMember,
                                                                                 ReihitsuFormatterHelpers.DetectEndOfLine(root),
                                                                                 targetTokenAnnotation,
                                                                                 targetFieldAnnotation);

        return new FormattingResult<Document>(document.WithSyntaxRoot(root.ReplaceNode(declaringType, declaringType.WithMembers(SyntaxFactory.List(updatedMembers)))), null);
    }

    /// <summary>
    /// Finds a node in a formatted context by following a marked token through the target's internal ancestor path
    /// </summary>
    /// <param name="targetNode">The original target node</param>
    /// <param name="formattedContext">The formatted containing node</param>
    /// <param name="targetTokenAnnotation">The annotation attached to the target's first token</param>
    /// <returns>The corresponding formatted node, or <see langword="null"/> when the marker or structure changed</returns>
    private static SyntaxNode FindCorrespondingNode(SyntaxNode targetNode,
                                                    SyntaxNode formattedContext,
                                                    SyntaxAnnotation targetTokenAnnotation)
    {
        var originalTokenParent = targetNode.GetFirstToken().Parent;

        if (originalTokenParent == null)
        {
            return null;
        }

        var ancestorKinds = new System.Collections.Generic.List<int>();
        var current = originalTokenParent;

        while (true)
        {
            ancestorKinds.Add(current.RawKind);

            if (current == targetNode)
            {
                break;
            }

            current = current.Parent;

            if (current == null)
            {
                return null;
            }
        }

        var annotatedTokens = formattedContext.GetAnnotatedTokens(targetTokenAnnotation)
                                              .Take(2)
                                              .ToArray();

        if (annotatedTokens.Length != 1)
        {
            return null;
        }

        current = annotatedTokens[0].Parent;

        for (var index = 0; index < ancestorKinds.Count; index++)
        {
            var ancestorKind = ancestorKinds[index];

            if (current == null || current.RawKind != ancestorKind)
            {
                return null;
            }

            if (index == ancestorKinds.Count - 1)
            {
                return current;
            }

            current = current.Parent;
        }

        return null;
    }

