using System.Collections.Generic;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

using Reihitsu.Core;
using Reihitsu.Formatter.Data.Enumerations;
using Reihitsu.Formatter.Pipeline.Core.Utilities;
using Reihitsu.Formatter.Pipeline.LineBreaks.Rewriter;

namespace Reihitsu.Formatter.Utilities;

/// <summary>
/// The entry-point code of <see cref="ReihitsuFormatter"/>: the guards that decide whether a tree is formatted at all, and
/// what an entry point computes about its input before the pipeline runs — the line ending, the column of a formatting
/// root's first token in its document, the construct it stands in, and its detached copy. Code fixes and the command-line
/// tool apply the same guards and computations through it. Phases do not use it; the facts they share live in
/// <c>Reihitsu.Core</c> and in <c>Pipeline/Core</c>
/// </summary>
internal static class ReihitsuFormatterHelpers
{
    #region Methods

    /// <summary>
    /// Detects the predominant end-of-line sequence in the syntax node.
    /// Falls back to <see cref="Environment.NewLine"/> if no end-of-line trivia is found
    /// </summary>
    /// <param name="node">The syntax node to analyze</param>
    /// <returns>The detected end-of-line sequence</returns>
    internal static string DetectEndOfLine(SyntaxNode node)
    {
        return LineEndingUtilities.DetectEndOfLine(node);
    }

    /// <summary>
    /// Checks whether the syntax tree contains any syntax errors.
    /// Files with syntax errors are skipped by the formatter
    /// </summary>
    /// <param name="syntaxTree">The syntax tree to check</param>
    /// <returns><see langword="true"/> if the tree has error-level diagnostics; otherwise, <see langword="false"/></returns>
    internal static bool HasSyntaxErrors(SyntaxTree syntaxTree)
    {
        return syntaxTree.GetDiagnostics()
                         .Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error);
    }

    /// <summary>
    /// Checks whether the source file is marked as auto-generated.
    /// Only the file header — the leading trivia of the first token — is inspected, so a
    /// comment that merely mentions the marker elsewhere in the file does not disable formatting.
    /// Supports both single-line and multi-line comments containing
    /// the &lt;auto-generated /&gt; marker
    /// </summary>
    /// <param name="root">The syntax root to inspect</param>
    /// <returns><see langword="true"/> if an auto-generated marker is present in the header; otherwise, <see langword="false"/></returns>
    internal static bool IsAutoGeneratedSource(SyntaxNode root)
    {
        var headerTrivia = root.GetFirstToken(includeZeroWidth: true).LeadingTrivia;

        foreach (var trivia in headerTrivia)
        {
            if (SyntaxTriviaUtilities.IsCommentTrivia(trivia) == false)
            {
                continue;
            }

            if (ContainsAutoGeneratedMarker(trivia.ToString()))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Checks whether the tree holds a hiding carrier (FMT-PIPE-033): a verbatim, raw, interpolated verbatim, or interpolated raw
    /// string, or a <c>/* */</c> or <c>/** */</c> comment, whose text spans lines, whose first character stands inside a
    /// conditional group that its <c>#endif</c> closes, and a line of whose text after the first starts, after whitespace, with
    /// <c>#</c>, optional whitespace, and the word <c>elif</c>, <c>else</c>, or <c>endif</c>. Whole-document formatting leaves such
    /// a tree unchanged, no code fix is offered in its document (SHARED-FIX-012), and the command-line tool and the playground
    /// name it as skipped; all of them ask this one definition
    /// </summary>
    /// <param name="root">The root of the tree</param>
    /// <returns><see langword="true"/> if the tree holds a hiding carrier; otherwise, <see langword="false"/></returns>
    internal static bool HoldsHidingCarrier(SyntaxNode root)
    {
        if (root.ContainsDirectives == false)
        {
            return false;
        }

        return GetOutermostConditionalGroups(root).Any(group => root.DescendantTokens(group)
                                                                    .Any(token => IsHidingCarrier(token, group)
                                                                                  || token.LeadingTrivia.Any(trivia => IsHidingCarrier(trivia, group))
                                                                                  || token.TrailingTrivia.Any(trivia => IsHidingCarrier(trivia, group))));
    }

    /// <summary>
    /// Captures the facts about the construct a target stands in in its document (FMT-PIPE-024), one flag for each decision
    /// of the line-break phase that reads the target's ancestors. Each flag is the answer that decision's own predicate gives
    /// for the target while it is still part of its document
    /// </summary>
    /// <param name="target">The target, still part of its document</param>
    /// <returns>The facts</returns>
    internal static RootConstruct CaptureRootConstruct(SyntaxNode target)
    {
        var facts = RootConstruct.None;

        if (target.Parent == null)
        {
            return facts;
        }

        if (target is AccessorDeclarationSyntax or AccessorListSyntax
            && AttributeTargetFormattingRewriter.StandsInOneLineProperty(target))
        {
            facts |= RootConstruct.OneLineProperty;
        }

        if (ListElementInteriorUtilities.LiesInListElement(target))
        {
            facts |= RootConstruct.ListElement;
        }

        if (target is BracketedArgumentListSyntax argumentList
            && LineBreakListRewriter.IsElementAccessArgumentList(argumentList, RootConstruct.None))
        {
            facts |= RootConstruct.ElementAccessArguments;
        }

        if (target is PatternSyntax
            && LineBreakInitializerRewriter.IsIntroducedByCaseLabel(target, RootConstruct.None))
        {
            facts |= RootConstruct.CaseLabelPattern;
        }

        if (target is InitializerExpressionSyntax initializer
            && LineBreakInitializerRewriter.IsAssignedCollectionInitializer(initializer, RootConstruct.None))
        {
            facts |= RootConstruct.AssignedCollectionInitializer;
        }

        return facts;
    }

    /// <summary>
    /// Returns a node as the root of a tree of its own (FMT-PIPE-023), with the parse options of the tree it came from, so
    /// that no phase reaches the code around it. A node without a parent is returned as it is
    /// </summary>
    /// <param name="node">The node</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>The node without a parent</returns>
    internal static SyntaxNode Detach(SyntaxNode node, CancellationToken cancellationToken)
    {
        return node.Parent == null
                   ? node
                   : CSharpSyntaxTree.Create((CSharpSyntaxNode)node, node.SyntaxTree.Options as CSharpParseOptions).GetRoot(cancellationToken);
    }

    /// <summary>
    /// Computes the column of a node-level formatting root's first token in its document (FMT-PIPE-017): the number of
    /// characters in front of it on its line, each one column, a tab included, except that a byte order mark at the start of
    /// the text counts as zero columns. The node-level entry points keep everything in front of that token as it stands
    /// (FMT-PIPE-018), so no character is measured as a phase would rewrite it
    /// </summary>
    /// <param name="token">The first token of the formatting root. Must belong to a syntax tree</param>
    /// <returns>The zero-based column of the token in its document</returns>
    internal static int ComputeDocumentColumn(SyntaxToken token)
    {
        var text = token.SyntaxTree.GetText();
        var lineStart = text.Lines.GetLineFromPosition(token.SpanStart).Start;
        var column = token.SpanStart - lineStart;

        if (lineStart == 0
            && column > 0
            && text[0] == '\uFEFF')
        {
            column--;
        }

        return column;
    }

    #endregion // Methods

    #region Private methods

    /// <summary>
    /// Determines whether comment text contains a generated-file marker
    /// </summary>
    /// <param name="commentText">The comment text to inspect</param>
    /// <returns><see langword="true"/> if a marker is present; otherwise, <see langword="false"/></returns>
    private static bool ContainsAutoGeneratedMarker(string commentText)
    {
        return commentText.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
               || commentText.IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0;
    }

    /// <summary>
    /// Gets the text between each outermost <c>#if</c> directive and the <c>#endif</c> that closes its group, active or not; a
    /// group without its <c>#endif</c> is left out
    /// </summary>
    /// <param name="root">The root of the tree</param>
    /// <returns>The spans in text order</returns>
    private static List<TextSpan> GetOutermostConditionalGroups(SyntaxNode root)
    {
        var groups = new List<TextSpan>();
        var depth = 0;
        var groupStart = 0;

        foreach (var trivia in root.DescendantTrivia())
        {
            if (trivia.IsKind(SyntaxKind.IfDirectiveTrivia))
            {
                if (depth == 0)
                {
                    groupStart = trivia.FullSpan.End;
                }

                depth++;
            }
            else if (trivia.IsKind(SyntaxKind.EndIfDirectiveTrivia)
                     && depth > 0)
            {
                depth--;

                if (depth == 0)
                {
                    groups.Add(TextSpan.FromBounds(groupStart, trivia.FullSpan.Start));
                }
            }
        }

        return groups;
    }

    /// <summary>
    /// Checks whether a token starts a hiding carrier inside a conditional group: a verbatim or raw string literal, or the start of
    /// an interpolated verbatim or interpolated raw string, whose text holds a line that another build reads as an
    /// <c>#elif</c>, <c>#else</c>, or <c>#endif</c> directive
    /// </summary>
    /// <param name="token">The token</param>
    /// <param name="group">The conditional group</param>
    /// <returns><see langword="true"/> if the token starts a hiding carrier in the group; otherwise, <see langword="false"/></returns>
    private static bool IsHidingCarrier(SyntaxToken token, TextSpan group)
    {
        if (group.Contains(token.SpanStart) == false)
        {
            return false;
        }

        switch (token.Kind())
        {
            case SyntaxKind.StringLiteralToken:
            case SyntaxKind.Utf8StringLiteralToken:
            case SyntaxKind.MultiLineRawStringLiteralToken:
            case SyntaxKind.Utf8MultiLineRawStringLiteralToken:
                return HoldsGroupEndingLine(token.Text);

            case SyntaxKind.InterpolatedVerbatimStringStartToken:
            case SyntaxKind.InterpolatedMultiLineRawStringStartToken:
                return token.Parent is InterpolatedStringExpressionSyntax interpolatedString
                       && HoldsGroupEndingLine(interpolatedString.ToString());

            default:
                return false;
        }
    }

    /// <summary>
    /// Checks whether a trivia is a hiding carrier inside a conditional group: a <c>/* */</c> or <c>/** */</c> comment whose text
    /// holds a line that another build reads as an <c>#elif</c>, <c>#else</c>, or <c>#endif</c> directive
    /// </summary>
    /// <param name="trivia">The trivia</param>
    /// <param name="group">The conditional group</param>
    /// <returns><see langword="true"/> if the trivia is a hiding carrier in the group; otherwise, <see langword="false"/></returns>
    private static bool IsHidingCarrier(SyntaxTrivia trivia, TextSpan group)
    {
        return (trivia.IsKind(SyntaxKind.MultiLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineDocumentationCommentTrivia))
               && group.Contains(trivia.SpanStart)
               && HoldsGroupEndingLine(trivia.ToFullString());
    }

    /// <summary>
    /// Checks whether a line of the text after its first starts, after whitespace, with <c>#</c>, optional whitespace, and the word
    /// <c>elif</c>, <c>else</c>, or <c>endif</c>. A text on one line holds no such line
    /// </summary>
    /// <param name="text">The text of a string literal or a comment</param>
    /// <returns><see langword="true"/> if the text holds such a line; otherwise, <see langword="false"/></returns>
    private static bool HoldsGroupEndingLine(string text)
    {
        if (text.IndexOf('#') < 0)
        {
            return false;
        }

        var lines = SourceText.From(text).Lines;

        for (var lineIndex = 1; lineIndex < lines.Count; lineIndex++)
        {
            var line = lines[lineIndex].ToString();
            var position = SkipWhitespace(line, 0);

            if (position >= line.Length
                || line[position] != '#')
            {
                continue;
            }

            position = SkipWhitespace(line, position + 1);

            if (StartsWithWord(line, position, "elif")
                || StartsWithWord(line, position, "else")
                || StartsWithWord(line, position, "endif"))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Gets the position of the first character at or behind a position that is not whitespace
    /// </summary>
    /// <param name="line">The line</param>
    /// <param name="position">The position to start at</param>
    /// <returns>The position, or the line's length when only whitespace follows</returns>
    private static int SkipWhitespace(string line, int position)
    {
        while (position < line.Length
               && char.IsWhiteSpace(line[position]))
        {
            position++;
        }

        return position;
    }

    /// <summary>
    /// Checks whether a word stands at a position of a line and is not followed by a letter, a digit, or an underscore
    /// </summary>
    /// <param name="line">The line</param>
    /// <param name="position">The position</param>
    /// <param name="word">The word</param>
    /// <returns><see langword="true"/> if the word stands there; otherwise, <see langword="false"/></returns>
    private static bool StartsWithWord(string line, int position, string word)
    {
        var end = position + word.Length;

        return end <= line.Length
               && string.CompareOrdinal(line, position, word, 0, word.Length) == 0
               && (end == line.Length || (char.IsLetterOrDigit(line[end]) == false && line[end] != '_'));
    }

    #endregion // Private methods
}