using System.Threading.Tasks;

using Microsoft.VisualStudio.TestTools.UnitTesting;

using Reihitsu.Analyzer.Rules.Performance;
using Reihitsu.Analyzer.Test.Base;

namespace Reihitsu.Analyzer.Test.Shared;

/// <summary>
/// Test methods for the shared rule that generated code is not analyzed, exercised through
/// <see cref="RH1003UseStringInterpolationInsteadOfStringConcatenationAnalyzer"/>, whose diagnostic needs no other
/// context than one expression
/// </summary>
[TestClass]
public class GeneratedCodeTests : AnalyzerTestsBase<RH1003UseStringInterpolationInsteadOfStringConcatenationAnalyzer>
{
    #region Constants

    /// <summary>
    /// A class whose concatenation chain RH1003 reports when the code is not generated
    /// </summary>
    private const string ViolatingClass = """
                                          internal class C
                                          {
                                              public string M(string name, int id)
                                              {
                                                  return "User: " + name + ", Id: " + id;
                                              }
                                          }
                                          """;

    #endregion // Constants

    #region Tests

    /// <summary>
    /// Verifying the violating class is reported when nothing marks it as generated, so the other tests of this class
    /// can only pass because of the generated-code marker
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    [TestMethod]
    public async Task ViolationIsReportedWhenTheCodeIsNotGenerated()
    {
        const string testCode = """
                                internal class C
                                {
                                    public string M(string name, int id)
                                    {
                                        return {|#0:"User: " + name + ", Id: " + id|};
                                    }
                                }
                                """;

        await Verify(testCode, Diagnostics(RH1003UseStringInterpolationInsteadOfStringConcatenationAnalyzer.DiagnosticId, AnalyzerResources.RH1003MessageFormat));
    }

    /// <summary>
    /// Verifying a file that starts with an auto-generated comment is not analyzed
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    [TestMethod]
    [Requirement("SHARED-DIAG-001")]
    public async Task FileWithAutoGeneratedHeaderIsNotAnalyzed()
    {
        await Verify("// <auto-generated/>\n" + ViolatingClass);
    }

    /// <summary>
    /// Verifying a file whose name marks it as generated is not analyzed
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    [TestMethod]
    [Requirement("SHARED-DIAG-001")]
    public async Task FileWithGeneratedFileNameIsNotAnalyzed()
    {
        await Verify(ViolatingClass,
                     test =>
                     {
                         test.TestState.Sources.Clear();
                         test.TestState.Sources.Add(("C.g.cs", ViolatingClass));
                     });
    }

    /// <summary>
    /// Verifying code marked with the generated-code attribute is not analyzed
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous operation</returns>
    [TestMethod]
    [Requirement("SHARED-DIAG-001")]
    public async Task CodeMarkedWithGeneratedCodeAttributeIsNotAnalyzed()
    {
        await Verify("[System.CodeDom.Compiler.GeneratedCode(\"Tool\", \"1.0\")]\n" + ViolatingClass);
    }

    #endregion // Tests
}