using Microsoft.CodeAnalysis;

using Reihitsu.Formatter;
using Reihitsu.Formatter.Utilities;

namespace Reihitsu.Cli.Abstractions;

/// <summary>
/// Default source formatter implementation that delegates to <see cref="ReihitsuFormatter"/>
/// </summary>
internal sealed class DefaultSourceFormatter : ISourceFormatter
{
    #region ISourceFormatter

    /// <inheritdoc/>
    public SyntaxTree FormatSyntaxTree(SyntaxTree syntaxTree, CancellationToken cancellationToken)
    {
        return ReihitsuFormatter.FormatSyntaxTree(syntaxTree, cancellationToken).Output;
    }

    /// <inheritdoc/>
    public UnsupportedSyntax FindUnsupportedSyntax(SyntaxTree syntaxTree, CancellationToken cancellationToken)
    {
        return ReihitsuFormatter.FindUnsupportedSyntax(syntaxTree.GetRoot(cancellationToken));
    }

    /// <inheritdoc/>
    public bool IsAutoGeneratedSource(SyntaxTree syntaxTree, CancellationToken cancellationToken)
    {
        var root = syntaxTree.GetRoot(cancellationToken);

        return ReihitsuFormatterHelpers.IsAutoGeneratedSource(root);
    }

    #endregion // ISourceFormatter
}