    /// <summary>
    /// Tests that UTF-8 BOM normalization preserves comment-marked generated files byte-for-byte in every command mode
    /// </summary>
    /// <param name="marker">The supported generated-source marker to place in the file header</param>
    /// <param name="mode">The command mode to exercise</param>
    /// <returns>A <see cref="Task"/> representing the asynchronous test operation</returns>
    [TestMethod]
    [DataRow("<auto-generated />", "normal")]
    [DataRow("<auto-generated />", "check")]
    [DataRow("<auto-generated />", "dry-run")]
    [DataRow("<autogenerated />", "normal")]
    [DataRow("<autogenerated />", "check")]
    [DataRow("<autogenerated />", "dry-run")]
    public async Task ExecuteAsyncUtf8BomSkipsCommentMarkedGeneratedFile(string marker, string mode)
    {
        // Arrange
        using (var tempDir = new TemporaryDirectoryFixture())
        {
            var generatedContent = AutoGeneratedMarkerFileTestData.Replace("<auto-generated />", marker, StringComparison.Ordinal);
            var generatedPath = tempDir.CreateFile("GeneratedByComment.cs", generatedContent);
            var originalBytes = await File.ReadAllBytesAsync(generatedPath, TestContext.CancellationToken);
            var checkOnly = string.Equals(mode, "check", StringComparison.Ordinal);
            var dryRun = string.Equals(mode, "dry-run", StringComparison.Ordinal);
            var handler = CreateHandler([tempDir.Path], checkOnly, dryRun, false, out var console, utf8Bom: true);

            // Act
            var exitCode = await handler.ExecuteAsync(TestContext.CancellationToken);

            // Assert
            Assert.AreEqual(ExitCodes.Success, exitCode);

            var actualBytes = await File.ReadAllBytesAsync(generatedPath, TestContext.CancellationToken);

            Assert.AreSequenceEqual(originalBytes, actualBytes);
            Assert.Contains(line => line == "Skipped 1 generated file(s).", console.StandardOutput);
            Assert.Contains(line => line.Contains("0 of 0 file(s)", StringComparison.Ordinal), console.StandardOutput);
        }
    }

    /// <summary>
    /// Tests that a recursive parent target processes an ordinary sibling without touching or reporting files in
    /// bin/ and obj/ directories
    /// </summary>
    /// <returns>A <see cref="Task"/> representing the asynchronous test operation</returns>
    [TestMethod]
    public async Task ExecuteAsyncSkipsBinAndObjDirectories()
    {
        // Arrange
        using (var tempDir = new TemporaryDirectoryFixture())
        {
            var normalPath = tempDir.CreateFile(Path.Combine("src", "Test.cs"), ValidInputTestData);
            var binPath = tempDir.CreateFile(Path.Combine("bin", "Debug", "Test.cs"), ValidInputTestData);
            var objPath = tempDir.CreateFile(Path.Combine("obj", "Debug", "Test.cs"), ValidInputTestData);

            var handler = CreateHandler([tempDir.Path], out var console);

            // Act
            var exitCode = await handler.ExecuteAsync(TestContext.CancellationToken);

            // Assert
            var normalContent = await File.ReadAllTextAsync(normalPath, TestContext.CancellationToken);
            var binContent = await File.ReadAllTextAsync(binPath, TestContext.CancellationToken);
            var objContent = await File.ReadAllTextAsync(objPath, TestContext.CancellationToken);
            var output = string.Join(Environment.NewLine, console.StandardOutput);

            Assert.AreEqual(ExitCodes.Success, exitCode);
            Assert.AreEqual(ValidInputResultData, normalContent);
            Assert.AreEqual(ValidInputTestData, binContent);
            Assert.AreEqual(ValidInputTestData, objContent);
            Assert.Contains(normalPath, output);
            Assert.DoesNotContain(binPath, output);
            Assert.DoesNotContain(objPath, output);
        }
    }

