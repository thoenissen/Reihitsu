    /// <summary>
    /// Creates one of the encodings recognized by <see cref="DefaultFileSystem"/>
    /// </summary>
    /// <param name="encodingName">The encoding identifier</param>
    /// <returns>The requested encoding, including its byte order mark when applicable</returns>
    private static Encoding CreateEncoding(string encodingName)
    {
        return encodingName switch
               {
                   "utf8-no-bom" => new UTF8Encoding(encoderShouldEmitUTF8Identifier: false),
                   "utf8-bom" => new UTF8Encoding(encoderShouldEmitUTF8Identifier: true),
                   "utf16-le" => Encoding.Unicode,
                   "utf16-be" => Encoding.BigEndianUnicode,
                   "utf32-le" => new UTF32Encoding(bigEndian: false, byteOrderMark: true),
                   "utf32-be" => new UTF32Encoding(bigEndian: true, byteOrderMark: true),
                   _ => throw new ArgumentOutOfRangeException(nameof(encodingName), encodingName, "Unsupported test encoding."),
               };
    }

    /// <summary>
    /// Asserts that a file keeps the expected encoding preamble and formatted content
    /// </summary>
    /// <param name="filePath">The formatted file path</param>
    /// <param name="expectedContent">The expected formatted content</param>
    /// <param name="expectedPreamble">The expected encoding preamble</param>
    /// <param name="cancellationToken">A token to monitor for cancellation requests</param>
    /// <returns>A <see cref="Task"/> representing the asynchronous assertion operation</returns>
    private static async Task AssertFileEncodingAndContentAsync(string filePath, string expectedContent, byte[] expectedPreamble, CancellationToken cancellationToken)
    {
        var fileSystem = new DefaultFileSystem();
        var fileRead = await fileSystem.ReadFileAsync(filePath, cancellationToken).ConfigureAwait(false);
        var actualPreamble = fileRead.Encoding.GetPreamble();

        Assert.AreSequenceEqual(expectedPreamble, actualPreamble);
        Assert.AreEqual(expectedContent, fileRead.Content);
    }

    /// <summary>
    /// Builds raw file bytes for <see cref="InvalidEncodingTestData"/> encoded with the specified encoding, with the
    /// <see cref="InvalidEncodingMarker"/> character's bytes replaced by an invalid byte sequence of the same length
    /// </summary>
    /// <param name="encoding">The encoding to use, including its BOM preamble</param>
    /// <param name="invalidSequence">The invalid byte sequence to substitute for the marker character</param>
    /// <returns>The raw file bytes</returns>
    private static byte[] CreateInvalidEncodingTestData(Encoding encoding, byte[] invalidSequence)
    {
        var contentBytes = encoding.GetBytes(InvalidEncodingTestData);
        var markerBytes = encoding.GetBytes(InvalidEncodingMarker.ToString());
        var markerIndex = contentBytes.AsSpan().IndexOf(markerBytes);

        Array.Copy(invalidSequence, 0, contentBytes, markerIndex, invalidSequence.Length);

        return [.. encoding.GetPreamble(), .. contentBytes];
    }

