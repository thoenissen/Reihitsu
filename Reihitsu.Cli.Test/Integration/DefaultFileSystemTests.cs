using System.Text;
using System.Threading.Tasks;

using Microsoft.CodeAnalysis.CSharp;
using Microsoft.VisualStudio.TestTools.UnitTesting;

using NSubstitute;

using Reihitsu.Cli.Abstractions;
using Reihitsu.Cli.Test.Helpers;

namespace Reihitsu.Cli.Test.Integration;

/// <summary>
/// Integration tests for <see cref="DefaultFileSystem"/>
/// </summary>
[TestClass]
public sealed class DefaultFileSystemTests
{
    #region Properties

    /// <summary>
    /// Test context for the current test
    /// </summary>
    public TestContext TestContext { get; set; }

    #endregion // Properties

    #region Tests

    /// <summary>
    /// Verifies that source-header reads stop before the full file for every supported encoding
    /// </summary>
    /// <param name="encodingName">The input encoding identifier</param>
    /// <returns>A task representing the asynchronous test operation</returns>
    [TestMethod]
    [DataRow("utf8-no-bom")]
    [DataRow("utf8-bom")]
    [DataRow("utf16-le")]
    [DataRow("utf16-be")]
    [DataRow("utf32-le")]
    [DataRow("utf32-be")]
    public async Task ReadSourceHeaderAsyncStopsAfterHeaderForSupportedEncoding(string encodingName)
    {
        const string marker = "// <auto-generated />\n";
        const string firstDeclaration = "namespace Test;\n";

        using (var tempDirectory = new TemporaryDirectoryFixture())
        {
            var content = $"{marker}{firstDeclaration}{new string(' ', 8192)}";
            var filePath = tempDirectory.CreateFile("Generated.cs", content, CreateEncoding(encodingName));
            var fileSystem = new DefaultFileSystem();

            var sourceHeader = await fileSystem.ReadSourceHeaderAsync(filePath, TestContext.CancellationToken);
            var syntaxTree = CSharpSyntaxTree.ParseText(sourceHeader,
                                                        cancellationToken: TestContext.CancellationToken);
            var formatter = new DefaultSourceFormatter();

            Assert.IsTrue(sourceHeader.StartsWith(marker, StringComparison.Ordinal));
            Assert.IsTrue(sourceHeader.Contains(firstDeclaration, StringComparison.Ordinal));
            Assert.IsLessThan(content.Length, sourceHeader.Length);
            Assert.IsTrue(formatter.IsAutoGeneratedSource(syntaxTree, TestContext.CancellationToken));
        }
    }

    /// <summary>
    /// Verifies that a comment delimiter split at an inspection boundary remains part of the source header
    /// </summary>
    /// <param name="inspectionLength">The scanner inspection length</param>
    /// <param name="commentDelimiter">The comment delimiter</param>
    /// <returns>A task representing the asynchronous test operation</returns>
    [TestMethod]
    [DataRow(4096, "//")]
    [DataRow(4096, "/*")]
    [DataRow(8192, "//")]
    [DataRow(8192, "/*")]
    [DataRow(16384, "//")]
    [DataRow(16384, "/*")]
    public async Task ReadSourceHeaderAsyncIncludesCommentDelimiterSplitAtInspectionBoundary(int inspectionLength,
                                                                                             string commentDelimiter)
    {
        using (var tempDirectory = new TemporaryDirectoryFixture())
        {
            var commentTerminator = commentDelimiter == "/*" ? " */" : string.Empty;
            var content = $"{new string(' ', inspectionLength - 1)}{commentDelimiter} <auto-generated />{commentTerminator}\ninternal class Generated {{ }}";
            var filePath = tempDirectory.CreateFile("Generated.cs", content);
            var fileSystem = new DefaultFileSystem();

            var sourceHeader = await fileSystem.ReadSourceHeaderAsync(filePath, TestContext.CancellationToken);
            var syntaxTree = CSharpSyntaxTree.ParseText(sourceHeader,
                                                        cancellationToken: TestContext.CancellationToken);
            var formatter = new DefaultSourceFormatter();

            Assert.IsTrue(formatter.IsAutoGeneratedSource(syntaxTree, TestContext.CancellationToken));
        }
    }

    /// <summary>
    /// Verifies that boundary-split generated markers do not trigger the noninteractive large-run error
    /// </summary>
    /// <returns>A task representing the asynchronous test operation</returns>
    [TestMethod]
    public async Task ExecuteAsyncLargeGeneratedRunWithBoundaryMarkerSkipsConfirmation()
    {
        using (var tempDirectory = new TemporaryDirectoryFixture())
        {
            var fileCount = FormatCommandHandler.LargeRunConfirmationThreshold + 1;
            var content = $"{new string(' ', 4095)}// <auto-generated />\ninternal class Generated {{ }}";

            for (var index = 0; index < fileCount; index++)
            {
                tempDirectory.CreateFile($"Generated{index}.cs", content);
            }

            var console = new CapturedConsoleOutput();
            var consoleInput = Substitute.For<IConsoleInput>();
            var dependencies = new FormatCommandDependencies(new DefaultFileSystem(),
                                                             console,
                                                             consoleInput,
                                                             new DefaultSourceFormatter(),
                                                             new DefaultDiffGenerator());
            var handler = new FormatCommandHandler([tempDirectory.Path],
                                                   checkOnly: false,
                                                   dryRun: false,
                                                   verbose: false,
                                                   force: false,
                                                   utf8Bom: true,
                                                   dependencies);

            var exitCode = await handler.ExecuteAsync(TestContext.CancellationToken);

            Assert.AreEqual(ExitCodes.Success, exitCode);
            Assert.Contains(line => line == $"Skipped {fileCount} generated file(s).", console.StandardOutput);

            consoleInput.DidNotReceive().ReadLine();
        }
    }

    #endregion // Tests

    #region Methods

    /// <summary>
    /// Creates one of the encodings recognized by <see cref="DefaultFileSystem"/>
    /// </summary>
    /// <param name="encodingName">The encoding identifier</param>
    /// <returns>The requested encoding, including its byte order mark when applicable</returns>
    private static Encoding CreateEncoding(string encodingName)
    {
        return encodingName switch
               {
                   "utf8-no-bom" => new UTF8Encoding(encoderShouldEmitUTF8Identifier: false),
                   "utf8-bom" => new UTF8Encoding(encoderShouldEmitUTF8Identifier: true),
                   "utf16-le" => Encoding.Unicode,
                   "utf16-be" => Encoding.BigEndianUnicode,
                   "utf32-le" => new UTF32Encoding(bigEndian: false, byteOrderMark: true),
                   "utf32-be" => new UTF32Encoding(bigEndian: true, byteOrderMark: true),
                   _ => throw new ArgumentOutOfRangeException(nameof(encodingName),
                                                              encodingName,
                                                              "Unsupported test encoding."),
               };
    }

    #endregion // Methods
}